// Merge agent-produced registry entries (registry/incoming/*.json) into registry/index.json,
// then regenerate lib/components.generated.ts (name → lazy component) from every "ready" entry whose file exists.
// Run: node web/scripts/merge-registry.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const web = join(dirname(fileURLToPath(import.meta.url)), "..")
const indexPath = join(web, "registry/index.json")
const incomingDir = join(web, "registry/incoming")
const index = JSON.parse(readFileSync(indexPath, "utf8"))
const byName = new Map(index.map((e) => [e.name, e]))

const DEFAULTS = { author: "Spatial", license: "MIT", price: "free", deps: [], tags: [], aliases: [], tier: 1, style: "default" }
let added = 0
let updated = 0
for (const f of existsSync(incomingDir) ? readdirSync(incomingDir).filter((f) => f.endsWith(".json")).sort() : []) {
  let entries
  try {
    entries = JSON.parse(readFileSync(join(incomingDir, f), "utf8"))
  } catch (e) {
    console.error(`skip ${f}: ${e.message}`)
    continue
  }
  for (const e of Array.isArray(entries) ? entries : []) {
    if (!e?.name || !/^[a-z0-9-]+$/.test(e.name)) continue
    const prev = byName.get(e.name)
    byName.set(e.name, { ...DEFAULTS, ...prev, ...e, file: e.file ?? `components/spatial/${e.name}.tsx` })
    prev ? updated++ : added++
  }
}

// Built-in layout container.
byName.set("frame", {
  ...DEFAULTS, ...byName.get("frame"), name: "frame", displayName: "Frame", category: "layout", kind: "layout",
  tags: ["frame", "auto-layout", "container", "row", "column", "grid", "arc"], aliases: ["group", "container", "stack"],
  description: "Auto-layout container: lines its children up in a row, column, grid or a curved wall around you.",
  file: "components/spatial/frame.tsx", status: "ready",
  props: [
    { name: "direction", type: "enum", options: ["row", "column", "grid", "arc"], default: "row" },
    { name: "gap", type: "number", min: 0, max: 0.5, default: 0.05 },
    { name: "padding", type: "number", min: 0, max: 0.3, default: 0.06 },
    { name: "columns", type: "number", min: 1, max: 8, default: 2 },
    { name: "radius", type: "number", min: 0.6, max: 4, default: 1.4 },
    { name: "background", type: "boolean", default: true },
  ],
})

// Truth comes from the filesystem: a file that exists is ready, a missing one is "soon".
// Components that failed visual QA (registry/qa-broken.json) are held back as "soon" until fixed.
const brokenPath = join(web, "registry/qa-broken.json")
const broken = new Set(existsSync(brokenPath) ? JSON.parse(readFileSync(brokenPath, "utf8")) : [])
const all = [...byName.values()].map((e) => {
  const has = existsSync(join(web, e.file ?? `components/spatial/${e.name}.tsx`))
  return { ...e, status: has && !broken.has(e.name) ? (e.status === "soon" && !e.file ? "soon" : "ready") : "soon" }
})
writeFileSync(indexPath, JSON.stringify(all, null, 2) + "\n")

const ready = all.filter((e) => e.status === "ready")
const ident = (n) => "C_" + n.replace(/[^A-Za-z0-9]/g, "_")
const lines = [
  "// GENERATED by web/scripts/merge-registry.mjs — do not edit. Re-run the script after adding a component.",
  'import { lazy, type ComponentType } from "react"',
  "",
  "// Lazy so the Studio/Quest only downloads the components actually placed. R3F's <Canvas> provides the Suspense boundary.",
  ...ready.map((e) => `const ${ident(e.name)} = lazy(() => import("@/${e.file.replace(/\.tsx?$/, "")}"))`),
  "",
  "export const components: Record<string, ComponentType> = {",
  ...ready.map((e) => `  ${JSON.stringify(e.name)}: ${ident(e.name)} as ComponentType,`),
  "}",
  "",
]
writeFileSync(join(web, "lib/components.generated.ts"), lines.join("\n"))
const cats = {}
for (const e of ready) cats[e.category] = (cats[e.category] ?? 0) + 1
console.log(`registry: ${all.length} entries (${ready.length} ready, +${added} new, ${updated} updated)`, cats)
